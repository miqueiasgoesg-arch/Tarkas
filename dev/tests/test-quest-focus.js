const assert=require('node:assert/strict');
const path=require('node:path');
const {setDataRoot}=require('../../src/shared/dataStorage');
setDataRoot(path.join(__dirname,'..','..','.tarkas-data'));
const {maps,mapDetail}=require('../../src/services/mapEngine');
const {planQuests,raidPlan}=require('../../src/services/questEngine');
const mapList=maps('regular');
const candidate=planQuests('regular',[],1).find(q=>q.status==='locked'&&q.map!=='Any'&&q.objectives.some(o=>o.zones.some(z=>z.position)||o.possibleLocations.some(l=>l.positions.length)));
assert.ok(candidate,'fixture must contain a locked quest with real map coordinates');
const map=mapList.find(m=>m.name===candidate.map);
assert.ok(map,'quest map must resolve from the structured Tarkov data');
const focused=raidPlan('regular',map.name,[],1,candidate.id).quests.find(q=>q.id===candidate.id);
assert.ok(focused,'selected locked quest must be included in the focused map plan');
const objective=focused.objectives.find(o=>o.zones.some(z=>z.mapId===map.id&&z.position)||o.possibleLocations.some(l=>l.mapId===map.id&&l.positions.length));
assert.ok(objective,'focused quest must retain the selected objective location');
const positions=[...objective.zones.filter(z=>z.mapId===map.id).map(z=>z.position),...objective.possibleLocations.filter(l=>l.mapId===map.id).flatMap(l=>l.positions)];
assert.ok(positions.length,'focused objective must provide one or more map markers');
if(map.calibration)assert.ok(positions.some(p=>p.overlay&&p.floor),'markers on calibrated maps must be projected to the actual map layer');
console.log('PASS focused locked quest:',candidate.name,'|',map.name,'|',positions.length,'location(s)');
